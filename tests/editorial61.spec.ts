import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const ledger = JSON.parse(readFileSync('docs/audit/editorial61/changes.json', 'utf8'))

test('22 corrected archives disclose pending publication and preserve noJS navigation/SEO', async ({ browser, isMobile }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, viewport: { width: isMobile ? 375 : 1440, height: 900 } })
  const page = await context.newPage()
  for (const row of ledger.pages) {
    const response = await page.goto(`http://127.0.0.1:3100${row.path}`)
    expect(response?.status(), row.path).toBe(200)
    expect(response?.headers()['x-robots-tag']).toBe('noindex, nofollow')
    await expect(page.getByRole('complementary', { name: 'Status review arsip' })).toContainText('PENDING_OWNER_APPROVAL')
    await expect(page.getByRole('complementary', { name: 'Status review arsip' })).toContainText('Cutover NO-GO')
    await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href', `https://kalkulatorharga.com${row.path}`)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(isMobile ? 375 : 1440)
  }
  await page.goto('http://127.0.0.1:3100/blog')
  await page.getByRole('link', { name: 'Cara hitung harga rata-rata saham setelah average down', exact: true }).first().click()
  await expect(page).toHaveURL(/\/blog\/kalkulator-average-down-saham-harga-rata-rata$/)
  await context.close()
})
test('specific finance, privacy and legal corrections are visible without invented official presets', async ({ page }, info) => {
  await page.goto('/blog/kalkulator-average-down-saham-harga-rata-rata')
  const article = page.locator('[data-legacy-source]')
  await expect(article).toContainText('Rp4.428,404344')
  await expect(article).toContainText('Rp6.628.387,50')
  await expect(article).toContainText('bukan fee resmi Stockbit')
  await expect(page.locator('a[href="/kalkulator/saham/average"]')).toHaveCount(0)
  await article.getByText('Contoh asumsi yang direkonsiliasi:', { exact: false }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('stock-editorial-correction.jpg'), scale: 'css', quality: 75 })
  await page.goto('/blog/harga-jual-minimum-marketplace')
  await expect(page.locator('[data-legacy-source]')).toContainText('Rp138.889')
  await expect(page.locator('[data-legacy-source]')).toContainText('Rp135.000')
  await expect(page.locator('[data-legacy-source]')).toContainText('bukan solver baru')
  await page.goto('/kebijakan-editorial')
  await expect(page.locator('[data-legacy-source]')).toContainText('retensi pada hosting/layanan operasional belum diverifikasi')
  await expect(page.locator('[data-legacy-source]')).not.toContainText('Username yang kamu ketik dikirim ke TikTok')
  await page.goto('/blog/pph-22-marketplace')
  await expect(page.locator('[data-legacy-source]')).toContainText('Pasal 8 menetapkan 0,5%')
  await expect(page.locator('[data-legacy-source]')).toContainText('belum dapat direkonsiliasi')
  await expect(page.locator('[data-legacy-source]')).toContainText('tanpa nominal pajak definitif')
  await page.goto('/biaya-admin-marketplace')
  await expect(page.locator('[data-legacy-source] caption')).toHaveCount(5)
  expect(await page.locator('[data-legacy-source] caption').allTextContents()).toEqual(expect.arrayContaining([expect.stringContaining('Snapshot klaim legacy')]))
})
